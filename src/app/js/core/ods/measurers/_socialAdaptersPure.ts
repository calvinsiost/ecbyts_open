/**
 * Social/economic ODS adapters — pure logic (F2 batch 2).
 *
 * Eight thin adapters over `measureGenericOds` covering all remaining
 * Calvin-mandated ODS that don't have a custom measurer:
 *
 *   ODS 1  No Poverty                — measureOds1Poverty
 *   ODS 2  Zero Hunger               — measureOds2Hunger
 *   ODS 4  Quality Education         — measureOds4Education
 *   ODS 5  Gender Equality           — measureOds5Gender
 *   ODS 7  Affordable Clean Energy   — measureOds7Energy
 *   ODS 9  Industry & Infrastructure — measureOds9Industry
 *   ODS 10 Reduced Inequalities      — measureOds10Inequality
 *   ODS 16 Peace & Justice           — measureOds16Peace
 *
 * Each function maps a small set of model-side fields to the
 * `GenericSubIndicator` shape with documented thresholds. Caller passes only
 * the fields it has; missing fields return null per-axis (anti-N1).
 *
 * Anti-requirements (SPEC_ODS_IMPACT_RISK §2):
 *   - N1: NaN/missing fields surface as null sub-scores
 *   - N5: zero deps beyond `_genericPure` + `OdsTier` type
 *   - N6: 1 file groups 8 quasi-identical adapters (no duplication)
 */

import { measureGenericOds, type GenericOdsResult } from './_genericPure.js';

// ─── ODS 1 — No Poverty ───────────────────────────────────────────────────────

export interface PovertyInput {
    /** Local payroll generated by the project (BRL/USD per year). */
    readonly localPayroll?: number | null;
    /** Number of vulnerable people in CadÚnico within the project's reach. */
    readonly vulnerableInReach?: number | null;
    /** Direct local jobs created by the project. */
    readonly localJobsCreated?: number | null;
    /** Saturation cap for "payroll per vulnerable person" (BRL/year). */
    readonly payrollPerVulnerableCap?: number;
}

export function measureOds1Poverty(input: PovertyInput): GenericOdsResult {
    const cap = input?.payrollPerVulnerableCap ?? 5000;
    return measureGenericOds({
        subIndicators: [
            {
                key: 'payrollPerVulnerable',
                numerator: input?.localPayroll ?? null,
                denominator: input?.vulnerableInReach ?? null,
                cap,
                direction: 'higher',
            },
            {
                key: 'localJobsCreated',
                numerator: input?.localJobsCreated ?? null,
                cap: 100,
                direction: 'higher',
            },
        ],
    });
}


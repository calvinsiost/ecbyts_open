// ─── ODS 5 — Gender Equality ──────────────────────────────────────────────────

export interface GenderInput {
    /** Headcount female employees on the project team. */
    readonly headcountFemale?: number | null;
    /** Headcount male employees on the project team. */
    readonly headcountMale?: number | null;
    /** Pay-gap ratio (female / male average pay). 1.0 = equal pay. */
    readonly payGapRatio?: number | null;
    /** Women in managerial positions [0, 1]. */
    readonly womenInManagement?: number | null;
}

export function measureOds5Gender(input: GenderInput): GenericOdsResult {
    const totalHeadcount =
        (Number(input?.headcountFemale) || 0) + (Number(input?.headcountMale) || 0);
    return measureGenericOds({
        subIndicators: [
            {
                key: 'femaleHeadcountRatio',
                numerator: input?.headcountFemale ?? null,
                denominator: totalHeadcount > 0 ? totalHeadcount : null,
                cap: 1,
                direction: 'higher',
            },
            {
                key: 'payGap',
                numerator: input?.payGapRatio ?? null,
                cap: 1,
                direction: 'higher',
            },
            {
                key: 'womenInManagement',
                numerator: input?.womenInManagement ?? null,
                cap: 1,
                direction: 'higher',
            },
        ],
    });
}

// ─── ODS 7 — Affordable & Clean Energy ────────────────────────────────────────

export interface EnergyInput {
    /** Renewable share of energy consumed by the project [0, 1]. */
    readonly renewableShare?: number | null;
    /** CO2eq emission per produced unit (kg CO2eq / unit). */
    readonly emissionIntensity?: number | null;
    /** Saturation cap for emission intensity (axis goes to 0 at cap). */
    readonly emissionIntensityCap?: number;
}

export function measureOds7Energy(input: EnergyInput): GenericOdsResult {
    const cap = input?.emissionIntensityCap ?? 10;
    return measureGenericOds({
        subIndicators: [
            {
                key: 'renewableShare',
                numerator: input?.renewableShare ?? null,
                cap: 1,
                direction: 'higher',
            },
            {
                key: 'emissionIntensity',
                numerator: input?.emissionIntensity ?? null,
                denominator: cap,
                cap: 1,
                direction: 'lower',
            },
        ],
    });
}

